-- Роли: первая привилегия — правка подтверждённой раздачи.
--
-- Игрок правит только то, что ещё не подтвердил; после подтверждения исправление идёт
-- через модератора, иначе за столом всегда найдётся желающий «переиграть» проигранную
-- раздачу. Первый модератор назначается руками:
--     UPDATE app_user SET role = 'moderator' WHERE nickname_normalized = '...';
ALTER TABLE app_user
    ADD COLUMN role VARCHAR(32) NOT NULL DEFAULT 'player'
        CHECK (role IN ('player', 'moderator', 'admin'));

-- Состояние стола на момент события: откат становится выбором строки, а не пересчётом
-- партии заново. Заполняется только у последнего события команды — промежуточные версии
-- наружу никогда не выходили, и откатываться к ним нельзя.
ALTER TABLE table_event
    ADD COLUMN table_state VARCHAR(32),
    ADD COLUMN game_state JSONB;
